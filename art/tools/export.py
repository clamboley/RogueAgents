"""Copies processed art into src/assets and writes src/assets/manifest.ts.

- Backgrounds: art/processed/bg-<biome>-<n>.png → src/assets/bg/<biome>-<n>.png, with their torch flames found
  automatically (clusters of bright, saturated warm pixels), so the game can add a flickering glow on top.
- Sprites: every art/processed/<group>/*.png with its meta.json (size and feet anchor).

Usage: python3 -I export.py   (run from the art directory)
"""

import glob
import json
import os
import re
import shutil
from collections import deque

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(os.path.dirname(ROOT), "src", "assets")
PROCESSED = os.path.join(ROOT, "processed")


def flames(path: str) -> list[tuple[int, int]]:
    """Centres of flame-coloured blobs: bright, saturated, warm pixels in the upper two thirds."""
    a = np.asarray(Image.open(path).convert("RGB")).astype(int)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    hot = (r > 200) & (g > 120) & (b < 140) & (r - b > 110)
    hot[int(a.shape[0] * 0.66) :] = False
    seen = np.zeros_like(hot)
    out = []
    for y, x in zip(*np.nonzero(hot)):
        if seen[y, x]:
            continue
        queue, pts = deque([(y, x)]), []
        seen[y, x] = True
        while queue:
            cy, cx = queue.popleft()
            pts.append((cy, cx))
            for dy in (-2, -1, 0, 1, 2):
                for dx in (-2, -1, 0, 1, 2):
                    ny, nx = cy + dy, cx + dx
                    if 0 <= ny < hot.shape[0] and 0 <= nx < hot.shape[1] and hot[ny, nx] and not seen[ny, nx]:
                        seen[ny, nx] = True
                        queue.append((ny, nx))
        if len(pts) >= 6:
            ys, xs = zip(*pts)
            out.append((round(sum(xs) / len(xs)), round(sum(ys) / len(ys))))
    return sorted(out)


def save_indexed(src: str, dest: str) -> None:
    """Saves an image as an indexed PNG with its exact colours: every asset has at most a few dozen, so nothing is lost
    and the file shrinks several times. Transparent pixels share palette index 0."""
    a = np.asarray(Image.open(src).convert("RGBA"))
    opaque = a[..., 3] > 0
    colors, inverse = np.unique(a[..., :3][opaque].reshape(-1, 3), axis=0, return_inverse=True)
    if len(colors) > 255:
        Image.open(src).save(dest, optimize=True)
        return
    index = np.zeros(a.shape[:2], dtype=np.uint8)
    index[opaque] = inverse.reshape(-1) + 1
    img = Image.fromarray(index, "P")
    img.putpalette([0, 0, 0, *colors.reshape(-1).tolist()])
    if not opaque.all():
        img.info["transparency"] = 0
        img.save(dest, optimize=True, transparency=0)
        return
    img.save(dest, optimize=True)


def ident(name: str) -> str:
    return re.sub(r"\W", "_", name)


def main():
    shutil.rmtree(ASSETS, ignore_errors=True)
    os.makedirs(os.path.join(ASSETS, "bg"))
    imports, backgrounds, sprites = [], {}, {}
    lights = json.load(open(os.path.join(ROOT, "lights.json")))

    for path in sorted(glob.glob(os.path.join(PROCESSED, "bg-*-[0-9].png"))):
        biome, n = re.match(r"bg-(\w+)-(\d+)\.png", os.path.basename(path)).groups()
        dest = f"bg/{biome}-{n}.png"
        save_indexed(path, os.path.join(ASSETS, dest))
        var = ident(f"bg_{biome}_{n}")
        imports.append(f'import {var} from "./{dest}"')
        torches = lights.get(os.path.basename(path)) or flames(path)
        backgrounds.setdefault(biome, []).append(f"{{ url: {var}, torches: {json.dumps(torches)} }}")

    for meta_path in sorted(glob.glob(os.path.join(PROCESSED, "*", "meta.json"))):
        group = os.path.basename(os.path.dirname(meta_path))
        os.makedirs(os.path.join(ASSETS, group), exist_ok=True)
        for name, m in json.load(open(meta_path)).items():
            dest = f"{group}/{name}.png"
            save_indexed(os.path.join(os.path.dirname(meta_path), f"{name}.png"), os.path.join(ASSETS, dest))
            var = ident(f"{group}_{name}")
            imports.append(f'import {var} from "./{dest}"')
            # Monsters stand on their whole body (a rat's tail is not its feet): centre their anchor.
            ax = round(m["w"] / 2, 1) if group.startswith("monsters") else m["ax"]
            sprites[name] = f'{{ url: {var}, w: {m["w"]}, h: {m["h"]}, ax: {ax} }}'

    lines = [
        "// Generated by art/tools/export.py. Do not edit by hand.",
        *imports,
        "",
        "/** A background and the centres of its torch flames, in world pixels. */",
        "export interface Background {",
        "  url: string",
        "  torches: [number, number][]",
        "}",
        "/** A sprite: its image, size, and the x of its feet within it. */",
        "export interface SpriteAsset {",
        "  url: string",
        "  w: number",
        "  h: number",
        "  ax: number",
        "}",
        "",
        "export const BACKGROUNDS: Record<string, Background[]> = {",
        *[f"  {b}: [{', '.join(items)}]," for b, items in backgrounds.items()],
        "}",
        "",
        "export const SPRITES: Record<string, SpriteAsset> = {",
        *[f'  "{n}": {s},' for n, s in sprites.items()],
        "}",
        "",
    ]
    with open(os.path.join(ASSETS, "manifest.ts"), "w") as f:
        f.write("\n".join(lines))
    print(f"{len(sprites)} sprites, backgrounds: { {b: len(v) for b, v in backgrounds.items()} }")
    for b, items in backgrounds.items():
        for item in items:
            print(" ", b, item[-60:])


if __name__ == "__main__":
    main()
